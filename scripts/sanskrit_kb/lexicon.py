"""
Sanskrit grammar read out of published tables.

Every form this module returns is looked up (or derived and then verified)
against the śabdapatha and the dhātupāṭha — none of it is typed by hand:

    shabda/data2.txt   9,007 stems, each with liṅga, gloss and all 24 subanta
                       cells, already sandhi-resolved
    dhatu/data.txt     2,259 roots with gaṇa, pada and Sanskrit gloss
    dhatu/dhatuforms_vidyut_shuddha_kartari.txt
                       every root x lakāra x puruṣa x vacana, generated by the
                       vidyut engine from the same sūtra system

Fetch them with `python3 scripts/fetch_vyakarana.py`; credit goes to
ashtadhyayi.com (https://github.com/ashtadhyayi-com/data).

    python3 -m scripts.sanskrit_kb.lexicon     # self-check
"""
from __future__ import annotations

import gzip
import json
from functools import lru_cache
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RAW = ROOT / "data" / "raw" / "vyakarana"

CASES = ("प्रथमा", "द्वितीया", "तृतीया", "चतुर्थी", "पञ्चमी", "षष्ठी", "सप्तमी",
         "सम्बोधनम्")
NUMBERS = ("एकवचनम्", "द्विवचनम्", "बहुवचनम्")
# the śabdapatha writes the cells case-major: case 1 eka/dvi/bahu, case 2 …
CELLS = tuple((c, n) for c in CASES for n in NUMBERS)
CELL_INDEX = {cell: i for i, cell in enumerate(CELLS)}

LINGA = {"P": "पुल्लिङ्गम्", "S": "स्त्रीलिङ्गम्", "N": "नपुंसकलिङ्गम्"}
PURUSHA = ("प्रथमपुरुष", "मध्यमपुरुष", "उत्तमपुरुष")
# display name -> table key. The tables carry both padas: p… parasmaipada, a… ātmanepada.
LAKARA_KEYS = {
    "लट्": ("plat", "alat"), "लिट्": ("plit", "alit"), "लुट्": ("plut", "alut"),
    "लृट्": ("plrut", "alrut"), "लोट्": ("plot", "alot"), "लङ्": ("plang", "alang"),
    "लिङ्": ("pvidhiling", "avidhiling"), "आशीर्लिङ्": ("pashirling", "aashirling"),
    "लुङ्": ("plung", "alung"), "लृङ्": ("plrung", "alrung"),
}
LAKARA = {name: name for name in LAKARA_KEYS}          # identity, for callers
LAKARA_KEY = {name: keys[0] for name, keys in LAKARA_KEYS.items()}
ALL_LAKARA_KEYS = tuple(k for keys in LAKARA_KEYS.values() for k in keys)
KEY_TO_LAKARA = {k: name for name, keys in LAKARA_KEYS.items() for k in keys}

# case names as they are declined in the locative (षष्ठी → षष्ठ्याम्, "in the 6th")
CASE_LOC = {"प्रथमा": "प्रथमायाम्", "द्वितीया": "द्वितीयायाम्", "तृतीया": "तृतीयायाम्",
            "चतुर्थी": "चतुर्थ्याम्", "पञ्चमी": "पञ्चम्याम्", "षष्ठी": "षष्ठ्याम्",
            "सप्तमी": "सप्तम्याम्", "सम्बोधनम्": "सम्बोधने"}
CASE_INS = {"प्रथमा": "प्रथमया", "द्वितीया": "द्वितीयया", "तृतीया": "तृतीयया",
            "चतुर्थी": "चतुर्थ्या", "पञ्चमी": "पञ्चम्या", "षष्ठी": "षष्ठ्या",
            "सप्तमी": "सप्तम्या", "सम्बोधनम्": "सम्बोधनेन"}
NUM_LOC = {"एकवचनम्": "एकवचने", "द्विवचनम्": "द्विवचने", "बहुवचनम्": "बहुवचने"}


def _load_json(name: str) -> dict:
    path = RAW / name
    if not path.exists():
        raise FileNotFoundError(
            f"{path} is missing — run `python3 scripts/fetch_vyakarana.py` first")
    return json.loads(path.read_text(encoding="utf-8"))


def table_paths() -> list[Path]:
    """Every place a packed table may live.

    Locally the module is `<repo>/scripts/sanskrit_kb/`, so the table is in
    `<repo>/serve/`. In the serverless bundle the module is
    `/var/task/serve/runtime/sanskrit_kb/` and the table is `/var/task/serve/`,
    i.e. two levels *down* from the module — so walk the ancestors rather than
    assuming one fixed root.
    """
    here = Path(__file__).resolve()
    out = [here.with_name("grammar_table.json.gz")]
    for base in here.parents:
        out.append(base / "grammar_table.json.gz")
        out.append(base / "serve" / "grammar_table.json.gz")
    out.append(Path.cwd() / "serve" / "grammar_table.json.gz")
    seen, uniq = set(), []
    for path in out:
        if path not in seen:
            seen.add(path)
            uniq.append(path)
    return uniq


A_STEM_ENDINGS = {
    ("प्रथमा", "एकवचनम्"): "", ("प्रथमा", "द्विवचनम्"): "औ", ("प्रथमा", "बहुवचनम्"): "ाः",
    ("द्वितीया", "एकवचनम्"): "म्", ("द्वितीया", "द्विवचनम्"): "औ", ("द्वितीया", "बहुवचनम्"): "ाः",
    ("तृतीया", "एकवचनम्"): "या", ("तृतीया", "द्विवचनम्"): "ाभ्याम्", ("तृतीया", "बहुवचनम्"): "ाभिः",
    ("चतुर्थी", "एकवचनम्"): "ै", ("चतुर्थी", "द्विवचनम्"): "ाभ्याम्", ("चतुर्थी", "बहुवचनम्"): "ाभ्यः",
    ("पञ्चमी", "एकवचनम्"): "ाः", ("पञ्चमी", "द्विवचनम्"): "ाभ्याम्", ("पञ्चमी", "बहुवचनम्"): "ाभ्यः",
    ("षष्ठी", "एकवचनम्"): "ाः", ("षष्ठी", "द्विवचनम्"): "योः", ("षष्ठी", "बहुवचनम्"): "ानाम्",
    ("सप्तमी", "एकवचनम्"): "ाम्", ("सप्तमी", "द्विवचनम्"): "योः", ("सप्तमी", "बहुवचनम्"): "ासु",
    ("सम्बोधनम्", "एकवचनम्"): "े", ("सम्बोधनम्", "द्विवचनम्"): "े", ("सम्बोधनम्", "बहुवचनम्"): "ाः",
}


def _a_stem(stem: str) -> dict[tuple, str]:
    """Regular ā-stem paradigm, for a feminine the śabdapatha does not attest."""
    if not stem.endswith("\u093e"):          # ends with the ā-mātrā
        return {}
    base = stem[:-1]
    out = {}
    for cell, ending in A_STEM_ENDINGS.items():
        if ending.startswith("ा"):
            out[cell] = base + ending
        elif ending in ("", "म्", "ै", "ाः", "योः", "ाम्", "े"):
            out[cell] = stem + ending
        else:
            out[cell] = stem + ending
    return out


class Lexicon:
    """Index over the śabdapatha, the dhātupāṭha and the tiṅanta tables."""

    def __init__(self) -> None:
        if (RAW / "shabda_data2.txt").exists() and (RAW / "dhatu_data.txt").exists():
            self._from_source()
        else:
            self._from_table()

    # -- packed table (deployment): everything the router needs, 1.7 MB gzipped
    def _from_table(self) -> None:
        for path in table_paths():
            if path.exists():
                with gzip.open(path, "rt", encoding="utf-8") as fh:
                    blob = json.load(fh)
                break
        else:
            raise FileNotFoundError(
                "no grammar table found — run `python3 scripts/fetch_vyakarana.py` "
                "and `python3 scripts/build_grammar_table.py`")
        self.stems = {}
        for word, entries in blob["stems"].items():
            self.stems[word] = [{"linga": e[0], "artha": e[1],
                                 "cells": e[2].split(";")} for e in entries]
        self.roots = {}
        self.root_by_index = {}
        for root, recs in blob["roots"].items():
            for rec in recs:
                record = {"root": root, "gana": rec.get("g", ""),
                          "pada": rec.get("p", ""), "artha": rec.get("a", ""),
                          "artha_english": "", "index": rec.get("i", ""),
                          "common": bool(rec.get("c", 0))}
                self.roots.setdefault(root, []).append(record)
                self.root_by_index[record["index"]] = record
        self.tin_tables = {}
        for root, recs in blob["roots"].items():
            for rec in recs:
                self.tin_tables[rec.get("i", "")] = {
                    k: v for k, v in rec.items()
                    if k in ALL_LAKARA_KEYS and isinstance(v, str)}
        self.source = "packed table"

    def _from_source(self) -> None:
        self.source = "raw sources"
        self.stems: dict[str, list[dict]] = {}
        for entry in _load_json("shabda_data2.txt")["data"]:
            forms = entry.get("forms", "")
            if not forms:
                continue
            cells = forms.split(";")
            if len(cells) != 24:
                continue
            self.stems.setdefault(entry["word"], []).append({
                "linga": entry.get("linga", ""),
                "artha": entry.get("artha", ""),
                "cells": cells,
            })

        self.roots: dict[str, list[dict]] = {}
        self.root_by_index: dict[str, dict] = {}
        for entry in _load_json("dhatu_data.txt")["data"]:
            rec = {"root": entry["dhatu"], "gana": entry.get("gana", ""),
                   "pada": entry.get("pada", ""), "artha": entry.get("artha", ""),
                   "artha_english": entry.get("artha_english", ""),
                   "index": entry.get("baseindex", ""),
                   "common": "common" in (entry.get("tags") or "")}
            self.roots.setdefault(rec["root"], []).append(rec)
            self.root_by_index[rec["index"]] = rec

        self.tin_tables: dict[str, dict[str, str]] = _load_json("dhatuforms_kartari.txt")

    # ---- nominals -------------------------------------------------------
    def stem_entries(self, stem: str, linga: str | None = None) -> list[dict]:
        out = self.stems.get(stem, [])
        return [e for e in out if linga is None or e["linga"] == linga]

    def has_stem(self, stem: str, linga: str | None = None) -> bool:
        return bool(self.stem_entries(stem, linga))

    def cells(self, stem: str, linga: str | None = None) -> dict[tuple, str] | None:
        entries = self.stem_entries(stem, linga)
        if not entries:
            return None
        return dict(zip(CELLS, entries[0]["cells"]))

    def cell(self, stem: str, case: str, number: str,
             linga: str | None = None) -> str | None:
        cells = self.cells(stem, linga)
        return None if cells is None else cells.get((case, number))

    def linga_of(self, stem: str) -> str | None:
        entries = self.stem_entries(stem)
        return LINGA.get(entries[0]["linga"]) if entries else None

    def feminine_of(self, stem: str, cell: tuple = ("प्रथमा", "एकवचनम्"),
                    allow_rule: bool = True) -> tuple[str, str, str] | None:
        """Masculine stem → feminine stem, form, and how it was found.

        Candidates are generated from the stem (`अश्व` → `अश्वा`; `बालक` →
        `बालिका`; `नर` → `नारी` is *not* generated) and then **verified against
        the śabdapatha**; a candidate that is not attested is still offered by
        rule, marked as such, because the paradigm is regular even when the word
        is rare.
        """
        # Devanagari writes a stem's final -a as a bare consonant, so the
        # candidates are built by suffixing the feminine endings directly.
        cands: list[tuple[str, str]] = []
        if stem.endswith("क"):
            cands.append((stem[:-1] + "िका", "क → इका"))
        cands.append((stem + "ा", "a-stem → ā-stem"))
        cands.append((stem + "ी", "→ ī-stem"))
        if stem.endswith("न्"):
            cands.append((stem[:-2] + "िनी", "न्-stem → इनी"))
        for cand, rule in cands:
            got = self.cell(cand, cell[0], cell[1], "S")
            if got:
                return cand, got, f"attested ({rule})"
        if not allow_rule or stem.endswith(("\u0903", "\u092e\u094d", "\u094d")):
            return None                              # an inflected form is no stem
        for cand, rule in cands:                     # not attested: regular ā-stem
            got = _a_stem(cand).get(cell)
            if got:
                return cand, got, f"rule, unattested word ({rule})"
        return None

    # ---- roots and tiṅ ------------------------------------------------
    def root_entries(self, root: str) -> list[dict]:
        return self.roots.get(root, [])

    def tin_cells(self, root: str, lakara: str = "लट्") -> list[tuple[dict, list[str]]]:
        """(dhātu record, 9 forms) for a root in a lakāra, one per pada."""
        out = []
        for rec in self.root_entries(root):
            table = self.tin_tables.get(rec["index"], {})
            for key in LAKARA_KEYS.get(lakara, ("plat",)):
                forms = table.get(key)
                if not forms:
                    continue
                cells = forms.split(";")
                if len(cells) == 9:
                    out.append((rec, cells))
        return out

    def tin(self, root: str, lakara: str, purusha: str, vacana: str) -> tuple[str, dict] | None:
        p = PURUSHA.index(purusha)
        v = NUMBERS.index(vacana)
        cells_and_recs = self.tin_cells(root, lakara)
        # a root can belong to two gaṇas (कृ is 5 and 8): prefer the one the
        # dhātupāṭha marks "common", which is the form actually in use
        cells_and_recs.sort(key=lambda pair: not pair[0].get("common"))
        for rec, cells in cells_and_recs:
            form = cells[p * 3 + v]
            if form:
                return form, rec
        return None

    def forms_of_root(self, root: str, lakara: str = "लट्") -> dict[str, dict]:
        """Every tiṅ form of a root in a lakāra, keyed by the form."""
        out: dict[str, dict] = {}
        for rec, cells in self.tin_cells(root, lakara):
            for i, form in enumerate(cells):
                out.setdefault(form, rec)
        return out

    def root_of_form(self, form: str, lakara: str | None = None) -> list[tuple[str, dict, str, str, str]]:
        """Reverse lookup: which roots produce this tiṅ form, and in which cell."""
        hits: list[tuple[str, dict, str, str, str]] = []
        keys = LAKARA_KEYS.get(lakara, ALL_LAKARA_KEYS) if lakara else ALL_LAKARA_KEYS
        for rec in self.root_by_index.values():
            table = self.tin_tables.get(rec["index"], {})
            for key in keys:
                cells = (table.get(key) or "").split(";")
                if len(cells) != 9:
                    continue
                for i, f in enumerate(cells):
                    if f == form:
                        hits.append((rec["root"], rec, KEY_TO_LAKARA[key],
                                     PURUSHA[i // 3], NUMBERS[i % 3]))
                        break
        return hits


@lru_cache(maxsize=1)
def lexicon() -> Lexicon:
    return Lexicon()


# convenience wrappers -------------------------------------------------
def cell(stem: str, case: str, number: str, linga: str | None = None) -> str | None:
    return lexicon().cell(stem, case, number, linga)


def decline(stem: str, linga: str | None = None) -> dict[tuple, str] | None:
    return lexicon().cells(stem, linga)


def feminine_of(stem: str) -> tuple[str, str, str] | None:
    return lexicon().feminine_of(stem)


def root_of_form(form: str) -> list[tuple[str, dict]]:
    return lexicon().root_of_form(form)


def _self_check() -> int:
    lex = lexicon()
    print(f"stems   {len(lex.stems):>6,}   cells {len(lex.stems) * 24:>8,}")
    print(f"roots   {len(lex.roots):>6,}   tiṅ tables {len(lex.tin_tables):>6,}")

    checks = [
        (("राम", "चतुर्थी", "एकवचनम्"), "रामाय"),
        (("राम", "तृतीया", "एकवचनम्"), "रामेण"),
        (("राम", "षष्ठी", "एकवचनम्"), "रामस्य"),
        (("लता", "चतुर्थी", "एकवचनम्"), "लतायै"),
        (("फल", "प्रथमा", "बहुवचनम्"), "फलानि"),
        (("अश्व", "प्रथमा", "एकवचनम्"), "अश्वः"),
        (("गज", "तृतीया", "एकवचनम्"), "गजेन"),
        (("मुनि", "षष्ठी", "बहुवचनम्"), "मुनीनाम्"),
    ]
    bad = 0
    for args, want in checks:
        got = lex.cell(*args)
        flag = "ok " if got == want else "FAIL"
        bad += got != want
        print(f"  {flag} {' '.join(args):<34} {got}")
    print(f"  feminine अश्व -> {lex.feminine_of('अश्व')}")
    print(f"  feminine बालक -> {lex.feminine_of('बालक')}")
    print(f"  कृ लट् प्रथम 3sg -> {lex.tin('कृ', 'लट्', 'प्रथमपुरुष', 'एकवचनम्')}")
    hits = lex.root_of_form("गच्छति")
    print(f"  गच्छति -> {[(h[0], h[2], h[3], h[4]) for h in hits][:3]}")
    hits = lex.root_of_form("करोति")
    print(f"  करोति -> {[(h[0], h[1]['gana'], h[2], h[3]) for h in hits][:4]}")
    return bad


if __name__ == "__main__":
    raise SystemExit(_self_check())
