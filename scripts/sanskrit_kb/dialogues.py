def generate(max_per_script: int = 8) -> list[dict]:
    """Expand every script across its slots into concrete dialogues."""
    out: list[dict] = []
    for d in DIALOGUES:
        keys = list(d.slots)
        combos = itertools.product(*(d.slots[k] for k in keys)) if keys else [()]
        for i, combo in enumerate(combos):
            if i >= max_per_script:
                break
            fill = dict(zip(keys, combo))
            exchanges = [(q.format(**fill), a.format(**fill)) for q, a in d.exchanges]
            out.append({"topic": d.topic, "exchanges": exchanges,
                        "standalone": min(d.standalone, len(exchanges))})
    return out


def to_line(exchanges: list[tuple[str, str]]) -> str:
    parts = []
    for q, a in exchanges:
        parts.append(f"<user> {q}")
        parts.append(f"<assistant> {a}")
    return " ".join(parts)


