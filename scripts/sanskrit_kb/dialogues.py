    for d in ds:
        for q, a in d["exchanges"]:
            if "{" in q or "{" in a:
                print(f"  ✗ unfilled slot: {q[:40]}")
                bad += 1
            if not a.endswith(("।", "?", "!")):
                print(f"  ✗ answer does not end a sentence: {a[:40]}")
                bad += 1
    turns = sum(len(d["exchanges"]) for d in ds)
    print(f"  {len(ds)} dialogues, {turns} exchanges, {bad} problems")
    return 1 if bad else 0


