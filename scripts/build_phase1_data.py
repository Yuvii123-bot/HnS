AGENT_BY_LEMMA = {n.lemma: n for n in morph.NOUNS}


def gen_morphology() -> list[str]:
    rows: list[str] = []
    for noun in morph.NOUNS:
        par = morph.paradigm(noun)
        base = noun.base()
        for case, cells in par.items():
            if case not in CASE_LOC:
                continue
            for num, form in cells.items():
                short = SHORT_NUM[num]
                # šabdarūpa: locative phrasing keeps the sandhi-free and unambiguous
                q = f"{base} शब्दस्य {CASE_LOC[case]} विभक्तौ {NUM_LOC[num]} रूपं किम्?"
                rows.append(f"<user> {q} <assistant> {form}")
                rows.append(f"<user> {form} इति पदं कस्यां विभक्तौ? <assistant> "
                            f"तत् पदं {CASE_LOC[case]} विभक्तौ {NUM_LOC[num]} च।")
                rows.append(f"<user> {form} इति पदं कस्मिन् वचने? <assistant> "
                            f"तत् पदं {NUM_LOC[num]}।")
        rows.append(f"<user> {base} शब्दः किंलिङ्गम्? <assistant> {noun.gender}।")
    return rows


def gen_verbs() -> list[str]:
    rows: list[str] = []
    for root, tbl in LAT.items():
        for num, (utt, madh, prath) in tbl.items():
            for label, form in ((PERSONS[2], utt), (PERSONS[1], madh), (PERSONS[0], prath)):
                q = f"{root} धातोः लटि {label} {num}ं किम्?"
                rows.append(f"<user> {q} <assistant> {form}।")
                rows.append(f"<user> {form} इति रूपं कस्मात् धातोः? <assistant> "
                            f"तत् रूपं {root} धातोः।")
        for num, (utt, madh, prath) in LANG[root].items():
            for label, form in ((PERSONS[2], utt), (PERSONS[1], madh), (PERSONS[0], prath)):
                rows.append(f"<user> {root} धातोः लङि {label} {num}ं किम्? <assistant> {form}।")
    return rows


def gen_comprehension(rng: random.Random, n: int = 1500) -> list[str]:
    """Passage + question whose answer is a span of the passage."""
    rows: list[str] = []
    roots = list(LAT)
    for _ in range(n):
        root = rng.choice(roots)
        s = AGENT_BY_LEMMA[rng.choice(AGENTS[root])]
        verb = LAT[root]["एकवचन"][2]                              # 3rd sing. present
        nom = morph.paradigm(s)["प्रथमा"]["एकवचनम्"]
        passage = f"{nom} {verb}।"
        rows.append(f"<user> {passage} कः {verb}? <assistant> {nom} {verb}।")
    return rows


def gen_correction(rng: random.Random, n: int = 800) -> list[str]:
    """Inject exactly one agreement error, ask for the correction."""
    rows: list[str] = []
    for _ in range(n):
        root = rng.choice(list(LAT))
        s = AGENT_BY_LEMMA[rng.choice(AGENTS[root])]
        nom = morph.paradigm(s)["प्रथमा"]["एकवचनम्"]
        good = LAT[root]["एकवचन"][2]
        bad = LAT[root]["बहुवचन"][2]
        rows.append(f"<user> अशुद्धं शोधय — {nom} {bad}। <assistant> {nom} {good}।")
    return rows


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--corpus", type=Path, default=ROOT / "data" / "clean_full" / "train.txt")
    ap.add_argument("--replay", type=Path, default=ROOT / "data" / "instruct_mix2" / "train.txt")
    ap.add_argument("--out", type=Path, default=ROOT / "data" / "phase1")
    ap.add_argument("--drill-repeat", type=int, default=6)
    ap.add_argument("--replay-repeat", type=int, default=1)
    ap.add_argument("--max-scripture-chars", type=int, default=0,
                    help="cap scripture volume so instruction data keeps its share")
    ap.add_argument("--scripture-share", type=float, default=0.88)
    args = ap.parse_args()

    rng = random.Random(7)
    scripture = [l for l in args.corpus.read_text(encoding="utf-8").splitlines() if l.strip()]
    if args.max_scripture_chars:
        kept, n = [], 0
        for line in scripture:
            if n >= args.max_scripture_chars:
                break
            kept.append(line); n += len(line)
        scripture = kept
    replay = [l for l in args.replay.read_text(encoding="utf-8").splitlines() if l.strip()]

    morph_rows = gen_morphology()
    verb_rows = gen_verbs()
    comp = gen_comprehension(rng)
    corr = gen_correction(rng)
    abstain = [f"<user> {q} <assistant> {a}" for q, a in ABSTAIN]

    targeted = morph_rows + verb_rows + comp + corr + abstain
    # drop anything that duplicates an eval question (leakage guard below double-checks)
    eval_path = ROOT / "data" / "phase1_eval.jsonl"
    eval_prompts = [json.loads(l)["prompt"] for l in eval_path.read_text(encoding="utf-8").splitlines() if l.strip()]
    def norm(s: str) -> str:
        return re.sub(r"\s+", " ", s).strip()
    banned = {norm(p) for p in eval_prompts}
    targeted = [r for r in targeted if norm(re.search(r"<user>\s*(.*?)\s*<assistant>", r).group(1)) not in banned]

    targeted_rep = targeted * args.drill_repeat
    rng.shuffle(targeted_rep)

    # interleave: after every ~k scripture lines, insert one targeted row so every
    # context window sees both; repeat replay a few times to protect the benchmark
    n_target = len(targeted_rep)
    share = args.scripture_share
    k = max(1, int(len(scripture) * (1 - share) / max(n_target * share, 1)))
    mixed: list[str] = []
    ti = 0
    for i, line in enumerate(scripture):
        mixed.append(line)
        if (i + 1) % k == 0 and ti < n_target:
            mixed.append(targeted_rep[ti]); ti += 1
    mixed.extend(targeted_rep[ti:])
    mixed.extend(replay * args.replay_repeat)
    mixed.extend(comp); mixed.extend(corr)     # a second pass on the weakest areas
    rng.shuffle(mixed)

    val_src = ROOT / "data" / "clean_full" / "val.txt"
    val = [l for l in val_src.read_text(encoding="utf-8").splitlines() if l.strip()][:3000]

    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "train.txt").write_text("\n".join(mixed) + "\n", encoding="utf-8")
    (args.out / "val.txt").write_text("\n".join(val) + "\n", encoding="utf-8")

    def toks(lines: list[str]) -> int:
        return sum(len(l) for l in lines) // 2          # ~0.49 tokens/char measured

    stats = {
        "scripture_lines": len(scripture),
        "targeted_unique": len(targeted),
        "targeted_rows_after_repeat": n_target,
        "by_family": {"morphology": len(morph_rows), "verbs": len(verb_rows),
                      "comprehension": len(comp), "correction": len(corr),
                      "abstain": len(abstain)},
        "replay_rows": len(replay) * args.replay_repeat,
        "scripture_chars_used": sum(len(x) for x in scripture),
        "train_rows": len(mixed),
        "est_tokens": toks(mixed),
        "drill_share_of_chars": round(
            sum(len(x) for x in targeted_rep) / max(sum(len(x) for x in mixed), 1), 4),
    }
    (args.out / "phase1_stats.json").write_text(
        json.dumps(stats, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(stats, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
