#!/usr/bin/env python3
"""
Phase 1 targeted training data, allocated by the Step-1 deficits.

Step 1 (reports/phase1_step1_eval.md) found 0% on dhaturupa, lakara, linga,
purusha, samasa, correction, relevance and abstention, and 10-50% on vibhakti,
shabdarupa, vacana and vocab. Scripture alone cannot fix any of that: it is not
question-answer shaped. So the mix is:

  scripture (data/clean_full)           general fluency / sandhi / compounds
  + morphology drills                   generated from the repo's declension
                                        engine and hand-verified verb tables
  + comprehension passages              generated, answer is a span of passage
  + correction pairs                    generated by injecting one controlled
                                        agreement error
  + abstention pairs                    "I do not know" for unanswerable facts
  + replay of data/instruct_mix2        protects the phase-2 benchmark
  + verse replay                        protects recitation (already inside mix2)

Everything is either attested text or derived from a verified paradigm table --
nothing is invented Sanskrit.

HELD OUT ON PURPOSE: the verb roots and noun cells that data/phase1_eval.jsonl
asks about. Training uses *other* roots (पच्, हस्, नी, स्था, ...) and other cells
so that any improvement on the eval is generalisation, not recall of the answer.

    python3 scripts/build_phase1_data.py
"""

