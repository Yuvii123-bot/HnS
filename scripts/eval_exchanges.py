#!/usr/bin/env python3
"""
Score 100 basic exchanges, including multi-turn ones, on held-out inputs.

Every prior assistant turn in a multi-turn item is generated by the model itself,
so what is measured is a real conversation with its own drift, not a scripted one.

Each item carries an `accept` list (any listed fragment in the reply passes) plus
quality checks that do not depend on the rubric: Devanagari only, non-empty, no
degenerate repetition, finished sentence.

    python3 scripts/eval_exchanges.py --bundle serve --label deployed
    python3 scripts/eval_exchanges.py --checkpoint artifacts/greet13/best.pt --label r13
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

SPECIAL = {"<eos>", "<user>", "<assistant>", "<pad>", "<bos>", "<unk>", "<system>"}
LATIN = re.compile(r"[A-Za-z]")


def norm(s: str) -> str:
    s = re.sub(r"[।॥!?,\.]", " ", s)
    return re.sub(r"\s+", " ", s).strip()


def score(answer: str, accept: list[str]) -> bool:
    n = norm(answer)
    return any(norm(a) and norm(a) in n for a in accept)


def repetition_ratio(answer: str) -> float:
    words = answer.split()
    if len(words) < 6:
        return 0.0
    bigrams = list(zip(words, words[1:]))
    counts = Counter(bigrams)
    return counts.most_common(1)[0][1] / len(bigrams)


# --------------------------------------------------------------------------- #
# backends
# --------------------------------------------------------------------------- #
class TorchBackend:
    def __init__(self, checkpoint: Path, tokenizer: Path) -> None:
        import torch
        from sanskrit_llm.data import token_feature_table
        from sanskrit_llm.model import load_checkpoint, stream_tokens
        from sanskrit_llm.tokenizer import AksharaTokenizer

        self._torch = torch
        self._stream = stream_tokens
        self.model, _, _ = load_checkpoint(checkpoint)
        self.model.eval()
        self.tok = AksharaTokenizer.load(tokenizer)
        self.feat = token_feature_table(self.tok)

    def reply(self, history: list[tuple[str, str]], message: str, max_new: int = 40) -> str:
        prompt = ""
        for user, assistant in history:
            prompt += f"<user> {user} <assistant> {assistant} "
        prompt += f"<user> {message} <assistant>"
        ids = self._torch.tensor([self.tok.encode(prompt)], dtype=self._torch.long)
        out = ""
        with self._torch.no_grad():
            for tid in self._stream(self.model, self.feat, ids, max_new_tokens=max_new,
                                    temperature=0.0, top_k=40, top_p=1.0,
                                    repetition_penalty=1.15, eos_id=None):
                piece = self.tok.vocab[tid]
                if piece in SPECIAL or "\n" in piece:
                    break
                out += piece
        return out.strip()


class NumpyBackend:
    """The deployed path: serve/model.npz through the same runtime the API uses."""

    def __init__(self, bundle: Path) -> None:
        import numpy as np
        from sanskrit_llm.numpy_lm import Runtime
        sys.path.insert(0, str(bundle / "runtime"))
        self.np = np
        self.rt = Runtime(bundle)
        self.tok = self.rt.tokenizer
        self.stop = {self.tok.pad_id, self.tok.bos_id, self.tok.unk_id,
                     self.tok.special_id("user"), self.tok.special_id("assistant"),
                     self.tok.special_id("system")}

    def reply(self, history: list[tuple[str, str]], message: str, max_new: int = 40) -> str:
        tok, rt = self.tok, self.rt
        prompt = ""
        for user, assistant in history:
            prompt += f"<user> {user} <assistant> {assistant} "
        prompt += f"<user> {message} <assistant>"
        ids = tok.encode(prompt)
        out = ""
        for tid, is_line_end in rt.model.sample(
            self.np.array(ids), temperature=0.0, top_k=40, top_p=1.0,
            repetition_penalty=1.15, max_new_tokens=max_new, max_lines=2,
            eos_id=tok.eos_id, feat_table=rt.feat_table, stop_token_ids=self.stop,
        ):
            if is_line_end:
                break
            piece = tok.vocab[tid]
            if piece in SPECIAL or piece.startswith("<") or LATIN.search(piece):
                break
            out += piece
        return out.strip()


# --------------------------------------------------------------------------- #
def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--checkpoint", type=Path)
    ap.add_argument("--bundle", type=Path)
    ap.add_argument("--tokenizer", type=Path, default=Path("artifacts/tokenizer.json"))
    ap.add_argument("--eval", type=Path, default=Path("data/conv_eval_100.jsonl"))
    ap.add_argument("--label", type=str, required=True)
    ap.add_argument("--out", type=Path, default=Path("reports"))
    ap.add_argument("--max-new", type=int, default=40)
    ap.add_argument("--verbose", action="store_true")
    args = ap.parse_args()

    if args.checkpoint:
        backend = TorchBackend(args.checkpoint, args.tokenizer)
        source = str(args.checkpoint)
    elif args.bundle:
        backend = NumpyBackend(args.bundle)
        source = str(args.bundle)
    else:
        raise SystemExit("give --checkpoint or --bundle")

    # Which prompts has the model actually been shown? Reporting a single number
    # over a set that mixes recall with generalisation would flatter the model.
    seen_prompts: set[str] = set()
    for name in ("data/greet/train.txt", "data/exchange_mix/train.txt"):
        fp = ROOT / name
        if not fp.exists():
            continue
        for line in fp.open(encoding="utf-8"):
            m = re.search(r"<user> (.*?) <assistant>", line)
            if m:
                seen_prompts.add(re.sub(r"[^\w\u0900-\u097F]+", "", m.group(1)).lower())

    items = [json.loads(line) for line in args.eval.open(encoding="utf-8")]
    rows = []
    by_cat: dict[str, list[bool]] = defaultdict(list)
    by_split: dict[str, list[bool]] = defaultdict(list)

    for item in items:
        history: list[tuple[str, str]] = []
        for turn in item.get("context", []):
            answer = backend.reply(history, turn, args.max_new)
            history.append((turn, answer))
        reply = backend.reply(history, item["prompt"], args.max_new)

        ok = score(reply, item["accept"])
        devanagari_only = not LATIN.search(reply)
        nonempty = bool(reply.strip())
        no_loop = repetition_ratio(reply) < 0.5
        finished = reply.rstrip().endswith(("।", "॥", "?", "!"))
        clean = devanagari_only and nonempty and no_loop and finished

        passed = ok and clean
        key = re.sub(r"[^\w\u0900-\u097F]+", "", item["prompt"]).lower()
        seen = key in seen_prompts
        by_cat[item["category"]].append(passed)
        by_split["seen" if seen else "unseen"].append(passed)
        rows.append({"id": item["id"], "category": item["category"], "seen_in_training": seen,
                     "context": item.get("context", []), "prompt": item["prompt"],
                     "reply": reply, "accept": item["accept"],
                     "content_ok": ok, "devanagari_only": devanagari_only,
                     "nonempty": nonempty, "no_loop": no_loop, "finished": finished,
                     "passed": passed})

        if args.verbose or not passed:
            mark = "ok  " if passed else "FAIL"
            why = "" if passed else (" (content)" if not ok else " (quality)")
            print(f"  [{mark}] {item['id']} {item['category']:11s} {item['prompt'][:30]:32s}"
                  f"-> {reply[:56]}{why}")

    total = len(rows)
    n_pass = sum(r["passed"] for r in rows)
    summary = {
        "label": args.label,
        "source": source,
        "items": total,
        "passed": n_pass,
        "accuracy": round(n_pass / total, 4),
        "content_ok": round(sum(r["content_ok"] for r in rows) / total, 4),
        "devanagari_only": round(sum(r["devanagari_only"] for r in rows) / total, 4),
        "finished_sentence": round(sum(r["finished"] for r in rows) / total, 4),
        "no_degenerate_loop": round(sum(r["no_loop"] for r in rows) / total, 4),
        "by_category": {cat: {"n": len(v), "pass": sum(v), "rate": round(sum(v) / len(v), 3)}
                        for cat, v in sorted(by_cat.items())},
        "by_seen": {k: {"n": len(v), "pass": sum(v), "rate": round(sum(v) / len(v), 3)}
                    for k, v in by_split.items()},
    }
    args.out.mkdir(parents=True, exist_ok=True)
    report = args.out / f"conv100_{args.label}.json"
    report.write_text(json.dumps({"summary": summary, "rows": rows},
                                 ensure_ascii=False, indent=1), encoding="utf-8")

    print()
    for cat, d in summary["by_category"].items():
        print(f"    {cat:11s} {d['pass']:3d}/{d['n']:<3d} {100*d['rate']:5.1f}%")
    for split, d in summary["by_seen"].items():
        print(f"    {'prompt seen in training' if split == 'seen' else 'prompt never seen':24s}"
              f" {d['pass']:3d}/{d['n']:<3d} {100*d['rate']:5.1f}%")
    print(f"\n{args.label}: {n_pass}/{total} = {100*n_pass/total:.1f}%"
          f"  (content {100*summary['content_ok']:.0f}%,"
          f" devanagari {100*summary['devanagari_only']:.0f}%,"
          f" finished {100*summary['finished_sentence']:.0f}%)")
    print(f"wrote {report}")


if __name__ == "__main__":
    main()
