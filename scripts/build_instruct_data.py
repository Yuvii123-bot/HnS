def question_forms(prompt: str, category: str) -> list[str]:
    """Natural alternative phrasings of the same question.

    These teach phrasing-invariance: the same fact asked plainly, politely, or
    as a reported question must get the same answer.
    """
    forms = [prompt]
    if not prompt.endswith("?"):
        return forms
    q = prompt[:-1]
    if category in ("dharma", "world", "glossary"):
        forms.append(f"कृपया वदतु, {q}?")
        forms.append(f"{q}? इति वदतु।")
    elif category in ("grammar", "reasoning"):
        forms.append(f"कृपया वदतु, {q}?")
    elif category == "numbers":
        forms.append(f"कृपया वदतु, {q}?")
    return forms


def user_turns(line: str) -> list[str]:
    """The <user> turns of a (possibly multi-turn) example."""
    turns, out = line.split("<user>")[1:], []
    for turn in turns:
        out.append(turn.split("<assistant>")[0].strip())
    return out


def build() -> tuple[list[str], dict, dict]:
    rows: list[str] = []
    row_cat: dict[str, str] = {}
    seen: set[str] = set()
    per_cat: dict[str, int] = {}

    for category, fid, q, a in FACTS:
        for form in question_forms(q, category):
            if category == "greeting":
                for extra in GREETING_VARIANTS.get(form, []):
                    line = f"<user> {extra} <assistant> {a}"
                    if line not in seen:
                        seen.add(line)
                        rows.append(line)
                        row_cat[line] = category
                        per_cat[category] = per_cat.get(category, 0) + 1
            line = f"<user> {form} <assistant> {a}"
            if line not in seen:
                seen.add(line)
                rows.append(line)
                row_cat[line] = category
                per_cat[category] = per_cat.get(category, 0) + 1

    for category, fid, text, _ in dialogue_pairs():
        line = f"<user> {text}"
        if line not in seen:
            seen.add(line)
            rows.append(line)
            row_cat[line] = category
            per_cat[category] = per_cat.get(category, 0) + 1

    # no evaluation prompt may appear as a training turn
    eval_set = {p.strip() for _, p, _ in EVAL_PROMPTS}
    dropped = [r for r in rows if any(t in eval_set for t in user_turns(r))]
    rows = [r for r in rows if not any(t in eval_set for t in user_turns(r))]

    facts = {(c, f) for c, f, _, _ in FACTS}
    stats = {
        "base_facts": len(facts),
        "pairs": len(rows),
        "dropped_eval_overlap": len(dropped),
        "per_category": dict(sorted(per_cat.items(), key=lambda kv: -kv[1])),
    }
    return rows, stats, row_cat


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=Path("data/instruct"))
    ap.add_argument("--val-ratio", type=float, default=0.06)
    ap.add_argument("--seed", type=int, default=13)
    args = ap.parse_args()

    rows, stats, row_cat = build()
    rng = random.Random(args.seed)

    # split by fact family: the fact id prefix decides the side, so a val pair
    # never re-states a training fact
    def fact_key(line: str) -> str:
        return line.split("<assistant>")[0].strip()[:24]

    keys = sorted({fact_key(r) for r in rows})
    rng.shuffle(keys)
    val_keys = set(keys[: max(1, int(len(keys) * args.val_ratio))])
    train = [r for r in rows if fact_key(r) not in val_keys]
    val = [r for r in rows if fact_key(r) in val_keys]
    rng.shuffle(train)
    rng.shuffle(val)

    # ------------------------------- quality control ---------------------
    problems = []
    for side, lines in (("train", train), ("val", val)):
        for line in lines:
            plain = line.replace("<user>", "").replace("<assistant>", "")
            if any("a" <= ch.lower() <= "z" for ch in plain):
                problems.append(f"{side}: latin char in {line[:60]}")
            answer = line.split("<assistant>", 1)[-1]
            if not any("\u0900" <= ch <= "\u097f" for ch in answer):
                problems.append(f"{side}: answer is not Devanagari in {line[:60]}")
            if "<assistant>" not in line or not line.split("<assistant>", 1)[1].strip():
                problems.append(f"{side}: empty answer in {line[:60]}")
            if "॥" in line.split("<assistant>", 1)[1]:
                problems.append(f"{side}: verse marker in answer {line[:60]}")
    if problems:
        for p in problems[:10]:
            print("QC:", p)
        raise SystemExit(f"{len(problems)} quality-control failures")

    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "train.txt").write_text("\n".join(train) + "\n", encoding="utf-8")
    (args.out / "val.txt").write_text("\n".join(val) + "\n", encoding="utf-8")
    with (args.out / "train.jsonl").open("w", encoding="utf-8") as fh:
        for line in train:
            fh.write(json.dumps({"category": row_cat.get(line, "unknown"),
                                 "text": line}, ensure_ascii=False) + "\n")
    with (args.out / "eval_prompts.jsonl").open("w", encoding="utf-8") as fh:
        for category, prompt, expected in EVAL_PROMPTS:
            fh.write(json.dumps({"category": category, "prompt": prompt,
                                 "expected": expected}, ensure_ascii=False) + "\n")
