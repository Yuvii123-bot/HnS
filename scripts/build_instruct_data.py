def dialogue_pairs() -> list[tuple[str, str, str, str]]:
    out = []
    openers = ["नमस्ते।", "सुप्रभातम्।", "नमस्ते। भवान् कथम् अस्ति?"]
    closers = ["धन्यवादः।", "अत्युत्तमम्। धन्यवादः।", "सम्यक्। धन्यवादः।"]
    cores = [f for f in FACTS if f[0] in ("dharma", "world", "conversation",
                                          "grammar", "glossary")]
    for i, (_, fid, q, a) in enumerate(cores[:420]):
        opener = openers[i % len(openers)]
        opener_answer = {
            "नमस्ते।": "नमस्ते!",
            "सुप्रभातम्।": "सुप्रभातम्!",
            "नमस्ते। भवान् कथम् अस्ति?": "नमस्ते! अहम् उत्तमः अस्मि।",
        }[opener]
        closer = closers[i % len(closers)]
        text = (f"{opener} <assistant> {opener_answer} <user> {q} "
                f"<assistant> {a} <user> {closer} <assistant> स्वागतम्।")
        out.append(("dialogue", f"dlg_{fid}", text, ""))
    return out


