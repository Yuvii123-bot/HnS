"""
Build a Sanskrit instruction-tuning dataset from curated Sanskrit material.

Every sentence here was written as Sanskrit *prose* with one property the old
verse-pair data lacked: an answer that actually answers its question.  Nothing
is translated, and nothing is machine-generated from English — the knowledge
base below is Sanskrit, and the pairs are Sanskrit surface forms of it.

Structure
---------
    FACTS        (category, fact_id, question, answer)  — hand written
    VARIANTS     each fact rendered as up to N natural question phrasings
    DIALOGUES    short multi-turn exchanges built from the same facts

Held-out evaluation prompts live in a separate table (`EVAL_PROMPTS`) that is
never used for training, and the split is made by *fact*, so a validation pair
is not a re-phrasing of a training pair.

    python3 scripts/build_instruct_data.py --out data/instruct
"""

